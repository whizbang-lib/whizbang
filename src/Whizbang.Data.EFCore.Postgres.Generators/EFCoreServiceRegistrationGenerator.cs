      sb.AppendLine($"// Generated by Whizbang.Data.EFCore.Postgres.Generators.EFCoreServiceRegistrationGenerator at {System.DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
      sb.AppendLine(DO_NOT_EDIT_COMMENT);
      sb.AppendLine(NULLABLE_ENABLE);
      sb.AppendLine();

      // Usings
      sb.AppendLine(USING_EF_CORE);
      sb.AppendLine("using Microsoft.Extensions.Configuration;");
      sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
      sb.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
      sb.AppendLine("using Npgsql;");
      sb.AppendLine("using Whizbang.Data.EFCore.Postgres;");
      // UseWhizbangFunctions() registers the custom EF method-call translators (e.g. the principal-filtering
      // AllowedPrincipalsContainsAny ?| translator). Collective apply no longer needs a custom translator —
      // it uses EF Core 10's native ComplexProperty().ToJson() nested SetProperty — but other features still
      // depend on these translators, so the registration stays.
      sb.AppendLine("using Whizbang.Data.EFCore.Postgres.Functions;");
      if (hasVectorFields) {
        sb.AppendLine("using Pgvector.EntityFrameworkCore;");
      }
      if (hasPhysicalFields) {
        sb.AppendLine("using Whizbang.Data.EFCore.Postgres.QueryTranslation;");
      }
      sb.AppendLine();

      sb.AppendLine($"namespace {dbContext.Namespace};");
      sb.AppendLine();

      sb.AppendLine(XML_DOC_SUMMARY_OPEN);
      sb.AppendLine($"/// Turnkey extension methods for registering {dbContext.ClassName} with dependency injection.");
      sb.AppendLine(XML_DOC_SUMMARY_CLOSE);
      sb.AppendLine($"public static class {dbContext.ClassName}Extensions {{");
      sb.AppendLine();

      // Generate Add{DbContextName} method
      sb.AppendLine(XML_DOC_SUMMARY_OPEN_INDENTED);
      sb.AppendLine($"  /// Registers {dbContext.ClassName} and its dependencies with the service collection.");
      sb.AppendLine("  /// Configures NpgsqlDataSource with JSON serialization and pgvector support (if needed).");
      sb.AppendLine(XML_DOC_SUMMARY_CLOSE_INDENTED);
      sb.AppendLine("  /// <param name=\"services\">The service collection to add services to</param>");
      sb.AppendLine("  /// <param name=\"connectionStringName\">Optional connection string name override. Default: " +
          $"\"{dbContext.ConnectionStringName}\"</param>");
      sb.AppendLine("  /// <returns>The service collection for method chaining</returns>");
      sb.AppendLine($"  public static IServiceCollection Add{dbContext.ClassName}(");
      sb.AppendLine("      this IServiceCollection services,");
      sb.AppendLine("      string? connectionStringName = null) {");
      sb.AppendLine();
      sb.AppendLine($"    var connectionStringKey = connectionStringName ?? \"{dbContext.ConnectionStringName}\";");
      sb.AppendLine();
      sb.AppendLine("    // Funnel the resolved key through to Whizbang notification options so the");
      sb.AppendLine("    // LISTEN/NOTIFY + commit-order stamper resolver looks up the same");
      sb.AppendLine("    // ConnectionStrings:{Key}-direct / ConnectionStrings:{Key} entries EF Core uses.");
      sb.AppendLine("    // Mirrors the same emit in the DbContextRegistrationRegistry callback so both");
      sb.AppendLine("    // wiring paths land at the SAME key. Guarded so an explicit");
      sb.AppendLine("    // Whizbang:Database:ConnectionStringKey in appsettings still wins.");
      sb.AppendLine("    services.PostConfigure<global::Whizbang.Core.Notifications.WhizbangNotificationOptions>(opts => {");
      sb.AppendLine("      if (string.IsNullOrWhiteSpace(opts.ConnectionStringKey)) {");
      sb.AppendLine("        opts.ConnectionStringKey = connectionStringKey;");
      sb.AppendLine("      }");
      sb.AppendLine("    });");
      sb.AppendLine();
