  /// <summary>
  /// Registers all Whizbang PostgreSQL stores with per-perspective hash tracking, and the managed-object reconcile:
  /// each schema initialization records the perspective tables' objects and retires the Whizbang-built ones the
  /// perspectives no longer declare (#1252).
  /// </summary>
  /// <param name="services">The service collection to register services with.</param>
  /// <param name="connectionString">The PostgreSQL connection string.</param>
  /// <param name="jsonOptions">The JSON serializer options configured with the application's WhizbangJsonContext.</param>
  /// <param name="initializeSchema">Whether to automatically initialize the Whizbang schema on startup.</param>
  /// <param name="perspectiveEntries">Per-perspective SQL entries from <c>PerspectiveSchemas.Entries</c>.</param>
  /// <param name="managedObjects">
  /// What those entries build, from <c>PerspectiveSchemas.ManagedObjects</c>; null leaves every object in place.
  /// </param>
  /// <param name="configureOptions">Configures the driver's options.</param>
  /// <docs>fundamentals/perspectives/managed-schema-objects</docs>
  /// <tests>tests/Whizbang.Data.Dapper.Postgres.Tests/DapperManagedObjectsTests.cs</tests>
  [SuppressMessage("Performance", "CA1848:Use the LoggerMessage delegates", Justification = "Startup logging doesn't need high performance optimization")]
  public static IServiceCollection AddWhizbangPostgres(
    this IServiceCollection services,
    string connectionString,
    JsonSerializerOptions jsonOptions,
    bool initializeSchema,
    KeyValuePair<string, string>[] perspectiveEntries,
    (string Table, string Kind, string Name, string DeclaredBy)[]? managedObjects,
    Action<PostgresOptions>? configureOptions = null) {
    ArgumentException.ThrowIfNullOrWhiteSpace(connectionString);
    ArgumentNullException.ThrowIfNull(jsonOptions);
    ArgumentNullException.ThrowIfNull(perspectiveEntries);

    // Configure options
    var options = new PostgresOptions();
    configureOptions?.Invoke(options);

    // Registration records what to initialize; the shared schema initializer does it at host start, with the
    // container (see _addSchemaInitialization).
    // Built per attempt with the container: a fresh declaration set plus the contributors, this instance, the
    // reconcile settings (a value that is not one fails the attempt) and the host's logger.
    _addSchemaInitialization(services, connectionString, options, initializeSchema, sp =>
      new PostgresSchemaInitializer(connectionString, perspectiveEntries) {
        // The registry rows row retention enrolls from, for every perspective the host's assemblies declared (#1548).
        PerspectiveRegistry = Whizbang.Core.Perspectives.PerspectiveRegistryPayloads.Registered,
        // What each table's model declares, read with the options the stores read with (#1874).
        DeclaredKeyTables = Whizbang.Data.Postgres.Perspectives.DeclaredKeyTable.ForSerializedModels(
          Whizbang.Core.Perspectives.PerspectiveDocumentModels.Registered, jsonOptions),
        ManagedObjects = managedObjects is null
          ? null
          : ManagedSchemaHostPass.Declared(ManagedSchemaObjectSet.FromDeclarations(managedObjects), sp),
        ManagedObjectSettings = ManagedSchemaSettings.Read(sp.GetService<IConfiguration>()),
        Logger = sp.GetRequiredService<ILogger<PostgresSchemaInitializer>>(),
        Instance = sp.GetRequiredService<IServiceInstanceProvider>(),
        Observers = [.. sp.GetServices<ISchemaInitializationObserver>()],
      });
    if (initializeSchema && managedObjects is not null) {
      // The periodic re-run of the reconcile, so a drop a start held back lands once the instance that still
      // declared the object is gone, without another deploy.
      services.AddScoped<Whizbang.Core.Workers.IMaintenanceStep>(sp =>
        new DapperManagedSchemaReconcileStep(
          connectionString,
          () => ManagedSchemaObjectSet.FromDeclarations(managedObjects),
          sp.GetRequiredService<ILogger<DapperManagedSchemaReconcileStep>>(),
          sp.GetRequiredService<TimeProvider>()));
    }

    // Register database infrastructure
    services.AddSingleton<IDbConnectionFactory>(_ =>
      new PostgresConnectionFactory(connectionString));

    // TURNKEY: which Postgres extensions this database can use, probed and reported at startup.
    _addExtensionProbe(services, connectionString);

    // TURNKEY: the maintenance step that completes perspective field moves after the start that made them:
    // it fills promoted columns for rows an instance still on the previous release wrote with the value only
    // in the document, settles demotions, and reports columns only a rebuild can restore (#1010). Idle
    // unless the schema pass armed a move.
    services.AddScoped<Whizbang.Core.Workers.IMaintenanceStep>(sp =>
      new DapperPhysicalColumnFillMaintenanceStep(
        connectionString,
        sp.GetService<ILogger<DapperPhysicalColumnFillMaintenanceStep>>(),
        sp.GetService<TimeProvider>()));
    _addStreamLifecycleBackfill(services, connectionString);
    _addPartitionMaintenance(services, connectionString);
    services.AddSingleton<IDbExecutor, DapperDbExecutor>();

    services.AddSingleton(options);
    // The documented cap on concurrent coordinator calls; the worker pipeline builds its gate from
    // WorkCoordinatorGateOptions, so carry it over (it used to reach nothing). Fill the gap only: a cap
    // the Whizbang:WorkCoordinatorGate section set is the operator's word.
    services.PostConfigure<WorkCoordinatorGateOptions>(gate => gate.MaxConcurrent ??= options.MaxInFlightCommands);
    services.AddSingleton(jsonOptions);

    services.TryAddSingleton<IPolicyEngine, PolicyEngine>();

    services.AddSingleton<IJsonbPersistenceAdapter<Whizbang.Core.Observability.IMessageEnvelope>, EventEnvelopeJsonbAdapter>();
    services.AddSingleton<JsonbSizeValidator>();

    // Registered as a FACTORY, not a type. A type-based registration is activated reflectively,
    // both by the container and by the decoration path that has to rebuild the inner store when
    // wrapping it. Naming the constructor here keeps that path free of reflection.
    services.AddScoped<IEventStore>(sp => new DapperPostgresEventStore(
      sp.GetRequiredService<IDbConnectionFactory>(),
      sp.GetRequiredService<IDbExecutor>(),
      sp.GetRequiredService<JsonSerializerOptions>(),
      sp.GetRequiredService<IJsonbPersistenceAdapter<Whizbang.Core.Observability.IMessageEnvelope>>(),
      sp.GetRequiredService<JsonbSizeValidator>(),
      sp.GetRequiredService<IPolicyEngine>(),
      sp.GetService<IPerspectiveInvoker>(),
      sp.GetRequiredService<ILogger<DapperPostgresEventStore>>(),
      // #1546: an appended event's kind is the one the dispatch path stamps, [Ephemeral] on a type included.
      sp.GetService<Whizbang.Core.IEphemeralModeResolver>()));
    services.AddSingleton<IWorkCoordinator>(sp =>
      new DapperWorkCoordinator(
        connectionString,
        jsonOptions,
        sp.GetService<ILogger<DapperWorkCoordinator>>()));
    services.AddSingleton<IRequestResponseStore, DapperPostgresRequestResponseStore>();
    services.AddSingleton<ISequenceProvider, DapperPostgresSequenceProvider>();

    // Register perspective snapshot and rewind options
    services.AddOptions<PerspectiveSnapshotOptions>();
    services.AddOptions<PerspectiveRewindOptions>();

    // Register perspective snapshot store and stream locker
    services.TryAddSingletonOverNullDefault<IPerspectiveSnapshotStore>(sp =>
      new DapperPerspectiveSnapshotStore(
        connectionString,
        sp.GetService<ILogger<DapperPerspectiveSnapshotStore>>()));
    services.TryAddSingletonOverNullDefault<IPerspectiveStreamLocker>(sp =>
      new DapperPerspectiveStreamLocker(
        connectionString,
        sp.GetRequiredService<Microsoft.Extensions.Options.IOptions<PerspectiveStreamLockOptions>>(),
        sp.GetService<ILogger<DapperPerspectiveStreamLocker>>()));

    services.DecorateEventStoreWithSyncTracking();

    // Message type registry populator — reconciles wh_message_type_registry at startup
    // using IMessageTypeCatalog (auto-registered by AddWhizbang via a module initializer).
    services.TryAddSingleton<IMessageTypeRegistryPopulator, DapperMessageTypeRegistryPopulator>();

    // Event-type rename tool — detects pinned-id drift and rewrites stored CLR type names.
    // Resolved explicitly (admin command / migration), not run automatically.
    services.TryAddSingleton<IEventTypeRenameTool, DapperEventTypeRenameTool>();

    // Purged streams stay purged, and the operator stream purge (shared Postgres implementations).
    AddStreamPurge(services, connectionString);

    // Cursor-checkpoint persistence for PerspectiveRebuilder. Without this, rebuild would
    // still update projection tables but wh_perspective_cursors would stay at whatever live
    // processing last wrote. See IPerspectiveCheckpointCompleter.
    services.TryAddSingleton<IPerspectiveCheckpointCompleter>(sp =>
      new DapperPostgresPerspectiveCheckpointCompleter(
        connectionString,
        sp.GetService<ILogger<DapperPostgresPerspectiveCheckpointCompleter>>()));

    // v0.502 DLQ — register IDeadLetterStore so InboxDispatchWorker can move failed
    // rows into wh_dead_letters. The store is singleton-safe (only stashes the
    // connection string at construction; opens connections on demand).
    _addDeadLetterStore(services, connectionString);
    _addDeadLetterRecoveryService(services, connectionString);
    _addPerspectiveTableSwapper(services, connectionString);
    _addTableStatistics(services, connectionString);

    // #1358: multi-stream commands, over this connection string; the worker polls, as there is no listen connection.
    services.AddWhizbangMultiStreamCommands(connectionString);

    // Reconcile wh_message_type_registry against the compile-time IMessageTypeCatalog.
    // Runs only when the schema was just initialized here (we know the table exists) and
    // AddWhizbang() has already registered IMessageTypeCatalog via its module initializer.
    //
    // 2026-06-12: replaced the prior `using var populatorProvider = services.BuildServiceProvider();`
    // pattern with an IHostedService that runs at host startup using the REAL provider —
    // no temp container, no shared-ConfigurationManager disposal trap. The hosted service
    // gracefully no-ops when IMessageTypeCatalog isn't registered (matches the prior null-
    // catalog log line).
    if (initializeSchema) {
      services.AddHostedService<MessageTypeRegistryReconciliationHostedService>();
    }

    return services;
  }

  /// <summary>
  /// Registers all Whizbang PostgreSQL stores with configurable connection retry options.
  /// Nothing connects at registration: when <paramref name="initializeSchema"/> is true the schema is initialized at
  /// host start by the shared schema initializer, which waits for the database with these retry settings and opens
  /// the schema-ready gate once the schema is in place.
  /// </summary>
  /// <param name="services">The service collection to register services with.</param>
  /// <param name="connectionString">The PostgreSQL connection string.</param>
  /// <param name="jsonOptions">The JSON serializer options configured with the application's WhizbangJsonContext.</param>
  /// <param name="initializeSchema">Whether to automatically initialize the Whizbang schema on startup. Default is false.</param>
  /// <param name="perspectiveSchemaSql">Optional perspective schema SQL generated by PerspectiveSchemaGenerator.</param>
  /// <param name="configureOptions">Optional configuration callback for PostgreSQL options (retry settings, etc.).</param>
  /// <returns>The service collection for chaining.</returns>
  /// <tests>tests/Whizbang.Data.Dapper.Postgres.Tests/DapperGateWiringTests.cs</tests>
  /// <tests>tests/Whizbang.Data.Dapper.Postgres.Tests/DapperGatePrecedenceTests.cs</tests>
  [SuppressMessage("Performance", "CA1848:Use the LoggerMessage delegates", Justification = "Startup logging doesn't need high performance optimization")]
  public static IServiceCollection AddWhizbangPostgres(
    this IServiceCollection services,
    string connectionString,
    JsonSerializerOptions jsonOptions,
    bool initializeSchema,
    string? perspectiveSchemaSql,
    Action<PostgresOptions>? configureOptions) {
    ArgumentException.ThrowIfNullOrWhiteSpace(connectionString);
    ArgumentNullException.ThrowIfNull(jsonOptions);

    // Configure options
    var options = new PostgresOptions();
    configureOptions?.Invoke(options);

    // Registration records what to initialize; the shared schema initializer does it at host start.
    _addSchemaInitialization(services, connectionString, options, initializeSchema, sp =>
      new PostgresSchemaInitializer(connectionString, perspectiveSchemaSql) {
        PerspectiveRegistry = Whizbang.Core.Perspectives.PerspectiveRegistryPayloads.Registered,
        DeclaredKeyTables = Whizbang.Data.Postgres.Perspectives.DeclaredKeyTable.ForSerializedModels(
          Whizbang.Core.Perspectives.PerspectiveDocumentModels.Registered, jsonOptions),
        Instance = sp.GetRequiredService<IServiceInstanceProvider>(),
        Observers = [.. sp.GetServices<ISchemaInitializationObserver>()],
      });

    // Register database infrastructure
    services.AddSingleton<IDbConnectionFactory>(_ =>
      new PostgresConnectionFactory(connectionString));

    // TURNKEY: which Postgres extensions this database can use, probed and reported at startup.
    _addExtensionProbe(services, connectionString);

    // TURNKEY: the maintenance step that completes perspective field moves after the start that made them:
    // it fills promoted columns for rows an instance still on the previous release wrote with the value only
    // in the document, settles demotions, and reports columns only a rebuild can restore (#1010). Idle
    // unless the schema pass armed a move.
    services.AddScoped<Whizbang.Core.Workers.IMaintenanceStep>(sp =>
      new DapperPhysicalColumnFillMaintenanceStep(
        connectionString,
        sp.GetService<ILogger<DapperPhysicalColumnFillMaintenanceStep>>(),
        sp.GetService<TimeProvider>()));
    _addStreamLifecycleBackfill(services, connectionString);
    _addPartitionMaintenance(services, connectionString);
    services.AddSingleton<IDbExecutor, DapperDbExecutor>();

    // Register PostgresOptions for components that need retry settings
    services.AddSingleton(options);
    // The documented cap on concurrent coordinator calls; the worker pipeline builds its gate from
    // WorkCoordinatorGateOptions, so carry it over (it used to reach nothing). Fill the gap only: a cap
    // the Whizbang:WorkCoordinatorGate section set is the operator's word.
    services.PostConfigure<WorkCoordinatorGateOptions>(gate => gate.MaxConcurrent ??= options.MaxInFlightCommands);

    // Register JSON serialization options
    services.AddSingleton(jsonOptions);

    // Register policy engine if not already registered
    services.TryAddSingleton<IPolicyEngine, PolicyEngine>();

    // Register JSONB persistence infrastructure
    services.AddSingleton<IJsonbPersistenceAdapter<Whizbang.Core.Observability.IMessageEnvelope>, EventEnvelopeJsonbAdapter>();
    services.AddSingleton<JsonbSizeValidator>();

    // Register Whizbang stores
    // IEventStore is registered as Scoped to allow injection of scoped IPerspectiveInvoker
    // Registered as a FACTORY, not a type. A type-based registration is activated reflectively,
    // both by the container and by the decoration path that has to rebuild the inner store when
    // wrapping it. Naming the constructor here keeps that path free of reflection.
    services.AddScoped<IEventStore>(sp => new DapperPostgresEventStore(
      sp.GetRequiredService<IDbConnectionFactory>(),
      sp.GetRequiredService<IDbExecutor>(),
      sp.GetRequiredService<JsonSerializerOptions>(),
      sp.GetRequiredService<IJsonbPersistenceAdapter<Whizbang.Core.Observability.IMessageEnvelope>>(),
      sp.GetRequiredService<JsonbSizeValidator>(),
      sp.GetRequiredService<IPolicyEngine>(),
      sp.GetService<IPerspectiveInvoker>(),
      sp.GetRequiredService<ILogger<DapperPostgresEventStore>>(),
      // #1546: an appended event's kind is the one the dispatch path stamps, [Ephemeral] on a type included.
      sp.GetService<Whizbang.Core.IEphemeralModeResolver>()));
    services.AddSingleton<IWorkCoordinator>(sp =>
      new DapperWorkCoordinator(
        connectionString,
        jsonOptions,
        sp.GetService<ILogger<DapperWorkCoordinator>>()));
    services.AddSingleton<IRequestResponseStore, DapperPostgresRequestResponseStore>();
    services.AddSingleton<ISequenceProvider, DapperPostgresSequenceProvider>();

    // Register perspective snapshot and rewind options
    services.AddOptions<PerspectiveSnapshotOptions>();
    services.AddOptions<PerspectiveRewindOptions>();

    // Register perspective snapshot store and stream locker
    services.TryAddSingletonOverNullDefault<IPerspectiveSnapshotStore>(sp =>
      new DapperPerspectiveSnapshotStore(
        connectionString,
        sp.GetService<ILogger<DapperPerspectiveSnapshotStore>>()));
    services.TryAddSingletonOverNullDefault<IPerspectiveStreamLocker>(sp =>
      new DapperPerspectiveStreamLocker(
        connectionString,
        sp.GetRequiredService<Microsoft.Extensions.Options.IOptions<PerspectiveStreamLockOptions>>(),
        sp.GetService<ILogger<DapperPerspectiveStreamLocker>>()));

    // TURNKEY: Wrap IEventStore with sync tracking decorator
    // This enables perspective synchronization by tracking emitted events
    // before they reach the database (cross-scope sync support)
    services.DecorateEventStoreWithSyncTracking();

    // Message type registry populator — reconciles wh_message_type_registry at startup
    // using IMessageTypeCatalog (auto-registered by AddWhizbang via a module initializer).
    services.TryAddSingleton<IMessageTypeRegistryPopulator, DapperMessageTypeRegistryPopulator>();

    // Event-type rename tool — detects pinned-id drift and rewrites stored CLR type names.
    // Resolved explicitly (admin command / migration), not run automatically.
    services.TryAddSingleton<IEventTypeRenameTool, DapperEventTypeRenameTool>();

    // Purged streams stay purged, and the operator stream purge (shared Postgres implementations).
    AddStreamPurge(services, connectionString);

    // Cursor-checkpoint persistence for PerspectiveRebuilder. Without this, rebuild would
    // still update projection tables but wh_perspective_cursors would stay at whatever live
    // processing last wrote. See IPerspectiveCheckpointCompleter.
    services.TryAddSingleton<IPerspectiveCheckpointCompleter>(sp =>
      new DapperPostgresPerspectiveCheckpointCompleter(
        connectionString,
        sp.GetService<ILogger<DapperPostgresPerspectiveCheckpointCompleter>>()));

    // v0.502 DLQ — register IDeadLetterStore so InboxDispatchWorker can move failed
    // rows into wh_dead_letters. The store is singleton-safe (only stashes the
    // connection string at construction; opens connections on demand).
    _addDeadLetterStore(services, connectionString);
    _addDeadLetterRecoveryService(services, connectionString);
    _addPerspectiveTableSwapper(services, connectionString);
    _addTableStatistics(services, connectionString);

    // #1358: multi-stream commands, over this connection string; the worker polls, as there is no listen connection.
    services.AddWhizbangMultiStreamCommands(connectionString);

    // See the first overload for the rationale: the prior `services.BuildServiceProvider()`
    // + `using` pattern silently disposed the host's shared ConfigurationManager. Defer
    // the populator run to host startup via an IHostedService that uses the REAL provider.
    if (initializeSchema) {
      services.AddHostedService<MessageTypeRegistryReconciliationHostedService>();
    }

    return services;
  }

  /// <summary>
  /// Records the schema work for host start: the shared schema initializer runs this driver's runner, then opens the
  /// schema-ready gate. Nothing here touches the database. Without schema initialization the gate still opens, since a
  /// schema provisioned out of band has nothing to wait for. The instance identity is registered when the host has
  /// none, so the instance registers itself and the managed-object reconcile can record what it declares.
  /// </summary>
  /// <param name="services">The service collection.</param>
  /// <param name="connectionString">The database.</param>
  /// <param name="options">The connection retry settings the start waits with.</param>
  /// <param name="initializeSchema">Whether this driver migrates the schema.</param>
  /// <param name="createInitializer">Builds the initializer, with the container, at each attempt.</param>
  /// <docs>data/turnkey-initialization</docs>
  /// <tests>tests/Whizbang.Data.Dapper.Postgres.Tests/DapperSchemaStartupTests.cs</tests>
  private static void _addSchemaInitialization(
      IServiceCollection services, string connectionString, PostgresOptions options, bool initializeSchema,
      Func<IServiceProvider, PostgresSchemaInitializer> createInitializer) {
    services.AddWhizbangInstanceIdentity();
    if (initializeSchema) {
      services.AddSingleton<ISchemaInitializationRunner>(sp => new DapperSchemaInitializationRunner(
        connectionString,
        options,
        () => createInitializer(sp),
        sp.GetRequiredService<ILogger<DapperSchemaInitializationRunner>>(),
        sp));
    }
    services.AddWhizbangSchemaInitialization();
  }

  /// <summary>
  /// Registers the purge markers that keep a purged perspective row purged (<see cref="IPerspectivePurgeMarkerStore"/>)
  /// and the operator stream purge (<see cref="IStreamPurger"/>), both the shared Postgres implementations over a
  /// connection of their own per call, and the repair for composite children filed under the composite's stream
  /// (<see cref="IFanoutChildRefiler"/>, #1798), and the built-in archive store (<c>IArchiveStore</c>, WS-3 S7). A host's
  /// own registration wins.
  /// </summary>
  /// <param name="services">The service collection.</param>
  /// <param name="connectionString">The service's database.</param>
  /// <docs>operations/infrastructure/purging-streams</docs>
  /// <tests>tests/Whizbang.Data.Dapper.Postgres.Tests/DapperStreamPurgeTests.cs:AddWhizbangPostgres_RegistersPurgeMarkersAndStreamPurger_BothOverloadsAsync</tests>
  /// <tests>tests/Whizbang.Data.Dapper.Postgres.Tests/DapperArchiveStoreTests.cs:AddWhizbangPostgres_RegistersTheTableArchiveStore_AndTheTruncateWritesThroughItAsync</tests>
  /// <tests>tests/Whizbang.Data.Dapper.Postgres.Tests/DapperStreamSealingTests.cs:Finalize_ThroughTheRegisteredFinalizer_SealsTheStream_AndTheNextAppendThrowsAsync</tests>
  internal static void AddStreamPurge(IServiceCollection services, string connectionString) {
    services.TryAddSingleton<IPerspectivePurgeMarkerStore>(_ =>
      new PostgresPerspectivePurgeMarkerStore(ct => OpenConnectionAsync(connectionString, ct)));
    services.TryAddSingleton<IStreamPurger>(sp =>
      new PostgresStreamPurger(
        ct => OpenConnectionAsync(connectionString, ct),
        logger: sp.GetService<ILogger<PostgresStreamPurger>>()));
    // The built-in archive store (WS-3 S7): the prefix truncate's archive path writes through it; a blob store
    // registered first wins.
    services.TryAddSingleton(_ => new PostgresArchiveConnection(ct => OpenConnectionAsync(connectionString, ct), Schema: null));
    services.TryAddSingleton<global::Whizbang.Core.Archival.IArchiveStore>(sp => {
      var database = sp.GetRequiredService<PostgresArchiveConnection>();
      return new PostgresTableArchiveStore(database.Open, database.Schema, sp.GetService<ILogger<PostgresTableArchiveStore>>());
    });
    // The maintenance step that performs the restores an AutoRestore append queued (#1738), through whichever archive store
    // is registered.
    services.TryAddEnumerable(ServiceDescriptor.Scoped<global::Whizbang.Core.Workers.IMaintenanceStep, ArchiveRestoreRequestStep>(
      ArchiveRestoreRequestStep.FromServices));
    // The stream finalizer (WS-3 S4), on the host's clock: sealing a stream is a developer's call, and every write path
    // then refuses the stream's appends.
    services.TryAddSingleton<global::Whizbang.Core.Lifecycle.IStreamFinalizer>(sp =>
      new PostgresStreamFinalizer(
        ct => OpenConnectionAsync(connectionString, ct),
        timeProvider: sp.GetService<TimeProvider>(),
        logger: sp.GetService<ILogger<PostgresStreamFinalizer>>()));
    services.TryAddSingleton<IFanoutChildRefiler>(sp =>
      new PostgresFanoutChildRefiler(
        ct => OpenConnectionAsync(connectionString, ct),
        sp.GetService<global::Whizbang.Core.IStreamIdExtractor>(),
        jsonOptions: global::Whizbang.Core.Serialization.JsonContextRegistry.CreateCombinedOptions(),
