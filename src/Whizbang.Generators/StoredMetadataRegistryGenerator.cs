using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Whizbang.Generators.Shared.Utilities;

namespace Whizbang.Generators;

/// <summary>
/// Registers, by name, every concrete type in the assembly whose stored metadata is kept full by
/// <c>[StoredMetadata(StoredMetadataForm.Full)]</c> on the type, a base class or an interface, into
/// <c>StoredMetadataRegistry</c> from a <c>[ModuleInitializer]</c>, so Whizbang.Core reads no attribute by reflection
/// (#1725). The nearest declaration wins: the type's own, then its base classes from the nearest, then its interfaces;
/// <c>StoredMetadataForm.Default</c> on a derived type takes it back to the write form.
/// </summary>
/// <docs>data/event-store#keeping-an-event-type-full</docs>
/// <tests>tests/Whizbang.Generators.Tests/StoredMetadataRegistryGeneratorTests.cs</tests>
[Generator]
public class StoredMetadataRegistryGenerator : IIncrementalGenerator {
  private const string STORED_METADATA_ATTRIBUTE = "Whizbang.Core.Attributes.StoredMetadataAttribute";
  private const int FULL = 1;

  /// <inheritdoc/>
  public void Initialize(IncrementalGeneratorInitializationContext context) {
    var full = context.SyntaxProvider.CreateSyntaxProvider(
        predicate: static (node, _) => AuditEventRegistryGenerator.IsAttributedOrDerivedTypeCandidate(node),
        transform: static (ctx, ct) => _extract(ctx, ct)
    ).Where(static name => name is not null);

    context.RegisterSourceOutput(full.Collect(), static (ctx, names) => _generate(ctx, names));
  }

  private static string? _extract(GeneratorSyntaxContext context, System.Threading.CancellationToken cancellationToken) {
    // An interface or abstract type is never an event's stored type, and an open generic has no stored name.
    // A type declaration always declares a named type.
    var symbol = (INamedTypeSymbol)context.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)context.Node, cancellationToken)!;
    if (symbol.IsAbstract || symbol.IsGenericType) {
      return null;
    }
    return _resolvedForm(symbol) == FULL ? TypeNameUtilities.BuildClrTypeName(symbol) : null;
  }

  // The nearest declaration's form: the type's own, its base classes from the nearest, then its interfaces.
  private static int? _resolvedForm(INamedTypeSymbol symbol) {
    for (var current = symbol; current is not null; current = current.BaseType) {
      if (_declaredForm(current) is int form) {
        return form;
      }
    }
    foreach (var face in symbol.AllInterfaces) {
      if (_declaredForm(face) is int form) {
        return form;
      }
    }
    return null;
  }

  private static int? _declaredForm(INamedTypeSymbol symbol) {
    var attribute = symbol.GetAttributes().FirstOrDefault(a => TypeNameUtilities.IsNamed(a.AttributeClass, STORED_METADATA_ATTRIBUTE));
    return attribute?.ConstructorArguments.FirstOrDefault().Value is int form ? form : null;
  }

  private static void _generate(SourceProductionContext context, ImmutableArray<string?> names) {
    var all = names.Where(static n => n is not null).Select(static n => n!).Distinct().OrderBy(static n => n, StringComparer.Ordinal).ToList();
    if (all.Count == 0) {
      return;
    }

    var source = new StringBuilder();
    source.AppendLine("// <auto-generated/>");
    source.AppendLine("#nullable enable");
    source.AppendLine();
    source.AppendLine("namespace Whizbang.Generated;");
    source.AppendLine();
    source.AppendLine("/// <summary>Registers this assembly's event types kept full by [StoredMetadata] into the StoredMetadataRegistry at load.</summary>");
    source.AppendLine("internal static class GeneratedStoredMetadataRegistrations {");
    source.AppendLine("  // CA2255: intentional ModuleInitializer for AOT-compatible cross-assembly registration");
    source.AppendLine("#pragma warning disable CA2255");
    source.AppendLine("  [global::System.Runtime.CompilerServices.ModuleInitializer]");
    source.AppendLine("#pragma warning restore CA2255");
    source.AppendLine("  internal static void Register() {");
    foreach (var name in all) {
      source.AppendLine($"    global::Whizbang.Core.Messaging.StoredMetadataRegistry.RegisterFull(\"{name.Replace("\\", "\\\\").Replace("\"", "\\\"")}\");");
    }
    source.AppendLine("  }");
    source.AppendLine("}");

    context.AddSource("StoredMetadataRegistry.g.cs", source.ToString());
  }
}
