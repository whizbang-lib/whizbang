CREATE OR REPLACE FUNCTION __SCHEMA__._wh_archive_manifest_location_from_locator() RETURNS TRIGGER AS $$
DECLARE
  v_parts TEXT[];
BEGIN
  -- Only a locator the Azure Blob store wrote names an object; any other row is left without a location, and the store
  -- refuses to read, restore or delete through it.
  v_parts := regexp_match(NEW.locator, '^azure-blob://([^/?]+)/([^?]+)\?');
  IF v_parts IS NOT NULL THEN
    NEW.location_id := __SCHEMA__._wh_archive_legacy_location_id('azure-blob', v_parts[1]);
    NEW.relative_path := v_parts[2];
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION __SCHEMA__._wh_archive_manifest_location_from_locator() IS
'353 (#2137): a manifest row written with only a locator (an instance of an older release, during a rolling deploy) is given its container''s legacy location and the rest of the locator as its relative path.';

DROP TRIGGER IF EXISTS wh_archive_manifest_location_from_locator_trg ON __SCHEMA__.wh_archive_manifest;
CREATE TRIGGER wh_archive_manifest_location_from_locator_trg
  BEFORE INSERT ON __SCHEMA__.wh_archive_manifest
  FOR EACH ROW WHEN (NEW.location_id IS NULL AND NEW.locator IS NOT NULL)
  EXECUTE FUNCTION __SCHEMA__._wh_archive_manifest_location_from_locator();

