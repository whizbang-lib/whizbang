CREATE OR REPLACE FUNCTION __SCHEMA__._wh_merge_archive_location(p_from BIGINT, p_to BIGINT) RETURNS VOID AS $$
BEGIN
  UPDATE __SCHEMA__.wh_archive_manifest SET location_id = p_to WHERE location_id = p_from;
  -- An object queued in both locations is one object once they are one location: keep one row.
  DELETE FROM __SCHEMA__.wh_archive_object_deletions q
  WHERE q.location_id = p_from
    AND EXISTS (SELECT 1 FROM __SCHEMA__.wh_archive_object_deletions t WHERE t.location_id = p_to AND t.relative_path = q.relative_path);
  UPDATE __SCHEMA__.wh_archive_object_deletions SET location_id = p_to WHERE location_id = p_from;
  DELETE FROM __SCHEMA__.wh_archive_locations WHERE location_id = p_from;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION __SCHEMA__._wh_merge_archive_location(BIGINT, BIGINT) IS
'353 (#2137): moves every manifest row and queued deletion of one archive location into another and removes the first. Moves no object.';

