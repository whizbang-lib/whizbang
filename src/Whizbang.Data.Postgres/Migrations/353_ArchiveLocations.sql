CREATE OR REPLACE FUNCTION __SCHEMA__.wh_backfill_archive_locations() RETURNS BIGINT AS $$
DECLARE
  v_rows BIGINT;
  v_queued BIGINT;
BEGIN
  -- Only rows with an Azure Blob locator and no location yet: a re-run finds none, and no object is touched.
  UPDATE __SCHEMA__.wh_archive_manifest m
  SET location_id = __SCHEMA__._wh_archive_legacy_location_id('azure-blob', p.parts[1]),
      relative_path = p.parts[2]
  FROM (SELECT stream_id, first_version, regexp_match(locator, '^azure-blob://([^/?]+)/([^?]+)\?') AS parts
        FROM __SCHEMA__.wh_archive_manifest WHERE location_id IS NULL) p
  WHERE m.stream_id = p.stream_id AND m.first_version = p.first_version AND p.parts IS NOT NULL;
  GET DIAGNOSTICS v_rows = ROW_COUNT;
  UPDATE __SCHEMA__.wh_archive_object_deletions q
  SET location_id = __SCHEMA__._wh_archive_legacy_location_id('azure-blob', p.parts[1]),
      relative_path = p.parts[2]
  FROM (SELECT ctid AS row_id, regexp_match(locator, '^azure-blob://([^/?]+)/([^?]+)\?') AS parts
        FROM __SCHEMA__.wh_archive_object_deletions WHERE location_id IS NULL) p
  WHERE q.ctid = p.row_id AND p.parts IS NOT NULL;
  GET DIAGNOSTICS v_queued = ROW_COUNT;
  RETURN v_rows + v_queued;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION __SCHEMA__.wh_backfill_archive_locations() IS
'353 (#2137): splits the Azure Blob locator of every manifest row and queued deletion that has no location yet into its container (one location per distinct container, no endpoint and no connection name recorded) and the rest (the relative path, starting at the stream). Returns the rows changed; a re-run changes none. Moves and deletes no object.';

SELECT __SCHEMA__.wh_backfill_archive_locations();

