-- Migration: 353_ArchiveLocations.sql
-- Date: 2026-11-07
-- Description: Archive locations are stored normalized, as logical information only, and every archive record names
--              its location by id plus a path that starts at its stream (#2137).
--
--              Before this migration each archive manifest row (268) and each queued object deletion (269) carried a
--              full locator, azure-blob://{container}/{stream}/{object}, and the Azure Blob store opened the container
--              named in the record whenever it differed from its configured one. A database copied to another
--              environment then read, restored and deleted the source environment's objects. Configuration now drives
--              every operation: a record never redirects one.
--
--              wh_archive_locations holds one row per location: the provider (azure-blob), the storage account's
--              endpoint (for example https://account.blob.core.windows.net, never a key, a signature or a connection
--              string), the logical connection name the service is configured with, and the container. Each manifest
--              row and each queued deletion holds that location_id and its relative_path, which starts at the stream
--              ({stream}/{object}) and says nothing about the account or the container. The store checks every
--              record's location against its configuration before it reads, restores or deletes anything, and throws
--              on a mismatch. Repointing an environment to another account or container is an update of the one
--              location row (wh_repoint_archive_location); no record is rewritten.
--
--              Existing records are backfilled by splitting each locator into its container (one location per
--              distinct container, its endpoint and connection name not recorded: the database never knew them) and
--              the rest (the relative path). The first lookup by a store configured for that container takes the
--              location as its own (wh_archive_location_id), so an upgrade needs no operator step; a location of any
--              other container still fails the check. No object is moved or deleted. An instance of an older release
--              that writes a locator during a rolling deploy has its row given a location and path by a trigger.
--
--              The locator columns become nullable: new records write none. The deletion queue's key moves from the
--              locator to (location_id, relative_path).
--
--              Number 353: above every number in use on develop and on open branches.
--
-- Dependencies: 268 (wh_archive_manifest), 269 (wh_archive_object_deletions, _wh_queue_archive_object_deletions)
-- Objects: wh_archive_locations, ux_archive_locations_location, ck_archive_locations_logical_only,
--          idx_archive_manifest_location, ux_archive_object_deletions_object, _wh_archive_legacy_location_id,
--          _wh_archive_manifest_location_from_locator, wh_archive_manifest_location_from_locator_trg,
--          wh_backfill_archive_locations, _wh_merge_archive_location, wh_archive_location_id, wh_repoint_archive_location,
--          _wh_queue_archive_object_deletions
-- Constants: the double-underscore tokens in this file (for example __SCHEMA__) are substituted at apply time (README rule 12).

CREATE TABLE IF NOT EXISTS __SCHEMA__.wh_archive_locations (
  location_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider         TEXT NOT NULL,
  account_endpoint TEXT NULL,
  connection_name  TEXT NULL,
  container        TEXT NOT NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Logical information only: an endpoint is scheme, host, port and path (no query, fragment or user information, where
  -- a signature or a key would sit), a connection name is a name, not a connection string, and a container is a name.
  CONSTRAINT ck_archive_locations_logical_only CHECK (
    (account_endpoint IS NULL OR account_endpoint !~ '[?#;@]')
    AND (connection_name IS NULL OR (connection_name <> '' AND connection_name !~ '[;=]'))
    AND container <> '' AND container !~ '[/?#;=@]')
);

-- One row per location. A location recorded before endpoints were (no endpoint, no name) is one row per container.
CREATE UNIQUE INDEX IF NOT EXISTS ux_archive_locations_location
  ON __SCHEMA__.wh_archive_locations (provider, COALESCE(account_endpoint, ''), COALESCE(connection_name, ''), container);

COMMENT ON TABLE __SCHEMA__.wh_archive_locations IS
  '353 (#2137): one row per archive location: provider, storage account endpoint, logical connection name and container, '
  'never a secret. Archive records (wh_archive_manifest, wh_archive_object_deletions) hold location_id plus a relative_path '
  'that starts at the stream. Repoint an environment by updating the row (wh_repoint_archive_location); a row with no '
  'endpoint and no name holds records written before 353 and is taken by the first lookup configured for its container.';

ALTER TABLE __SCHEMA__.wh_archive_manifest
  ADD COLUMN IF NOT EXISTS location_id BIGINT NULL
    CONSTRAINT fk_archive_manifest_location REFERENCES __SCHEMA__.wh_archive_locations (location_id);
ALTER TABLE __SCHEMA__.wh_archive_manifest ADD COLUMN IF NOT EXISTS relative_path TEXT NULL;
ALTER TABLE __SCHEMA__.wh_archive_manifest ALTER COLUMN locator DROP NOT NULL;

-- A merge moves every record of one location: found by this index, not a scan of the manifest.
CREATE INDEX IF NOT EXISTS idx_archive_manifest_location ON __SCHEMA__.wh_archive_manifest (location_id);

ALTER TABLE __SCHEMA__.wh_archive_object_deletions
  ADD COLUMN IF NOT EXISTS location_id BIGINT NULL
    CONSTRAINT fk_archive_object_deletions_location REFERENCES __SCHEMA__.wh_archive_locations (location_id);
ALTER TABLE __SCHEMA__.wh_archive_object_deletions ADD COLUMN IF NOT EXISTS relative_path TEXT NULL;
ALTER TABLE __SCHEMA__.wh_archive_object_deletions DROP CONSTRAINT IF EXISTS wh_archive_object_deletions_pkey;
ALTER TABLE __SCHEMA__.wh_archive_object_deletions ALTER COLUMN locator DROP NOT NULL;

COMMENT ON COLUMN __SCHEMA__.wh_archive_manifest.locator IS
  '353 (#2137): the full locator rows written before 353 carried; kept readable, never used to find an object. New rows write NULL.';
COMMENT ON COLUMN __SCHEMA__.wh_archive_manifest.relative_path IS
  '353 (#2137): the object inside its location, starting at the stream ({stream}/{object}); the account and container are the location''s.';

