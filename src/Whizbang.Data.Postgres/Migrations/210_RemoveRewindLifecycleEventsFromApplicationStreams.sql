-- Migration: 210_RemoveRewindLifecycleEventsFromApplicationStreams.sql
-- Date: 2026-10-14
-- Description: DATA (not schema) migration (#1360). Builds before the fix appended PerspectiveRewindStarted and
--              PerspectiveRewindCompleted into the application stream they rewound, taking version numbers in
--              it. The fixed build writes them to a stream of their own; this removes the ones already written,
--              with their bodies and side rows.
--
--              What is removed: a rewind lifecycle event in a stream that also holds a non-lifecycle event. A
--              stream holding nothing but lifecycle events is where the fixed build writes them, and is left
--              alone. Events are taken one by one, never as Started/Completed pairs: a failed rewind publishes
--              Started and never Completed.
--
--              The version gaps are left. Appends take the stream's highest version plus one, so a gap is never
--              refilled and never collides, and nothing reads versions as consecutive. Renumbering would
--              invalidate wh_perspective_snapshots.snapshot_version, a stored copy of an event's version that
--              rewind selection and the reap coverage gate both compare against (209); a wrong value there
--              skips events or releases a body a rewind still needs.
--
--              An event something still points at (a cursor, a snapshot, an archive or destruction-hold row, a
--              purge marker, an emission claim, a collective ordering head) is kept rather than forced out.
--
--              Gated on the wh_settings row 'rewind_lifecycle_event_cleanup_version' (absent = not run, 1 =
--              done), so startup reads one flag and the population is never rescanned. Enumerated once into a
--              worklist and removed in bounded slices, so a large event store cannot exceed the migration's
--              command timeout.
-- Dependencies: 209 (snapshot_version), and every table named in the guard below.

CREATE TABLE IF NOT EXISTS __SCHEMA__.wh_rewind_cleanup_todo (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID NOT NULL
);
CREATE TABLE IF NOT EXISTS __SCHEMA__.wh_rewind_cleanup_cursor (
  only_row BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (only_row),
  last_seq BIGINT NOT NULL DEFAULT 0
);
INSERT INTO __SCHEMA__.wh_rewind_cleanup_cursor (only_row, last_seq) VALUES (TRUE, 0) ON CONFLICT DO NOTHING;

-- One scan to enumerate the work, only before the pass is done and only while the list is empty, so a replay
-- cannot double up.
DO $wb$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM __SCHEMA__.wh_rewind_cleanup_todo)
     AND COALESCE((SELECT setting_value::INTEGER FROM __SCHEMA__.wh_settings
                   WHERE setting_key = 'rewind_lifecycle_event_cleanup_version'), 0) < 1 THEN
    INSERT INTO __SCHEMA__.wh_rewind_cleanup_todo (event_id)
    SELECT e.event_id
    FROM __SCHEMA__.wh_event_store e
    WHERE split_part(e.event_type, ',', 1) IN ('Whizbang.Core.Events.System.PerspectiveRewindStarted',
                                              'Whizbang.Core.Events.System.PerspectiveRewindCompleted')
      AND EXISTS (
        SELECT 1 FROM __SCHEMA__.wh_event_store x
        WHERE x.stream_id = e.stream_id
          AND split_part(x.event_type, ',', 1) NOT IN ('Whizbang.Core.Events.System.PerspectiveRewindStarted',
                                                       'Whizbang.Core.Events.System.PerspectiveRewindCompleted'))
    ORDER BY e.ctid;
  END IF;
END
$wb$;

