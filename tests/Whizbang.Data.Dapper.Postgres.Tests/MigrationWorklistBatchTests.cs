  // ── 063: normalize aggregate type names on the event store ────────────────────────────────────
  [Test]
  public async Task TheAggregateTypeNormalizationReadsItsWorklistNotTheStoreAsync() {
    await using var c = new NpgsqlConnection(ConnectionString);
    await c.OpenAsync();
    await _assertWorklistInstalledAsync(c, "wh_normalize_aggregate_type_batch");
    try {
      await _execAsync(c, @"
        DELETE FROM public.wh_event_store;
        DROP TABLE IF EXISTS public.wh_aggtype_norm_todo;
        DROP TABLE IF EXISTS public.wh_aggtype_norm_cursor;
        CREATE TABLE public.wh_aggtype_norm_todo (
          seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id UUID NOT NULL);
        CREATE TABLE public.wh_aggtype_norm_cursor (
          only_row BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (only_row), last_seq BIGINT NOT NULL DEFAULT 0);
        INSERT INTO public.wh_aggtype_norm_cursor VALUES (TRUE, 0);
        -- The guard reads this: at version 3 there is nothing to normalize.
        INSERT INTO public.wh_settings (setting_key, setting_value, value_type, description)
        VALUES ('clr_type_name_format_version', '2', 'integer', 'test')
        ON CONFLICT (setting_key) DO UPDATE SET setting_value = '2';");
      await _execAsync(c, $@"
        INSERT INTO public.wh_event_store
          (event_id, stream_id, aggregate_id, aggregate_type, event_type, version, created_at)
        SELECT gen_random_uuid(), gen_random_uuid(), gen_random_uuid(),
               'Stale.Name',                       -- differs from split_part(event_type, ',', 1)
               'Some.Event' || g || ', Some.Assembly', g, NOW()
        FROM generate_series(1, {ROWS}) g;
        INSERT INTO public.wh_aggtype_norm_todo (event_id)
        SELECT event_id FROM public.wh_event_store
        WHERE event_type NOT LIKE '%[[%'
          AND aggregate_type IS DISTINCT FROM split_part(event_type, ',', 1) ORDER BY ctid;
        ANALYZE public.wh_event_store; ANALYZE public.wh_aggtype_norm_todo;");

      var r = await _runPassAsync(c, "wh_normalize_aggregate_type_batch",
        _seqTupSql("wh_event_store", "wh_aggtype_norm_todo", "wh_aggtype_norm_cursor"));
      Console.WriteLine($"[063] calls={r.Calls} seq_tup_read={r.SequentialRows}");

      await Assert.That(await _scalarAsync(c, @"
        SELECT count(*) FROM public.wh_event_store
        WHERE event_type NOT LIKE '%[[%'
          AND aggregate_type IS DISTINCT FROM split_part(event_type, ',', 1);")).IsEqualTo(0L);
      await _assertLinearAsync(r.SequentialRows);
    } finally {
      await _execAsync(c, @"
        DELETE FROM public.wh_event_store;
        DROP TABLE IF EXISTS public.wh_aggtype_norm_todo;
        DROP TABLE IF EXISTS public.wh_aggtype_norm_cursor;");
    }
  }

  // ── 162: seed the inbox work-state side table ─────────────────────────────────────────────────
  [Test]
  public async Task TheInboxStateSeedReadsItsWorklistNotTheInboxAsync() {
    await using var c = new NpgsqlConnection(ConnectionString);
    await c.OpenAsync();
    await _assertWorklistInstalledAsync(c, "wh_seed_inbox_state_batch");
    try {
      await _execAsync(c, @"
        DELETE FROM public.wh_inbox_state;
        DELETE FROM public.wh_inbox;
        -- The backfill's guard looks for the columns 162 moves out to the side table, so the
        -- pre-migration shape has to come back or the only reachable path is that guard.
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS processed_at TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS instance_id UUID;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS lease_expiry TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS attempts INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS scheduled_for TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS failure_reason INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS error TEXT;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS chain_emitted_at TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS status INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS received_at TIMESTAMPTZ DEFAULT NOW();
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS partition_number INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS priority INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS is_event BOOLEAN DEFAULT TRUE;
        DROP TABLE IF EXISTS public.wh_inbox_state_seed_todo;
        DROP TABLE IF EXISTS public.wh_inbox_state_seed_cursor;
        CREATE TABLE public.wh_inbox_state_seed_todo (
          seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, message_id UUID NOT NULL);
        CREATE TABLE public.wh_inbox_state_seed_cursor (
          only_row BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (only_row), last_seq BIGINT NOT NULL DEFAULT 0);
        INSERT INTO public.wh_inbox_state_seed_cursor VALUES (TRUE, 0);");
      await _execAsync(c, $@"
        INSERT INTO public.wh_inbox
          (message_id, handler_name, message_type, event_data, metadata, source_service_id)
        SELECT gen_random_uuid(), 'h', 'Some.Type, Some.Assembly', '{{}}'::jsonb, '{{}}'::jsonb,
               gen_random_uuid()
        FROM generate_series(1, {ROWS}) g;
        INSERT INTO public.wh_inbox_state_seed_todo (message_id)
        SELECT i.message_id FROM public.wh_inbox i
        WHERE NOT EXISTS (SELECT 1 FROM public.wh_inbox_state s WHERE s.message_id = i.message_id)
        ORDER BY i.ctid;
        ANALYZE public.wh_inbox; ANALYZE public.wh_inbox_state_seed_todo;");

      var r = await _runPassAsync(c, "wh_seed_inbox_state_batch",
        _seqTupSql("wh_inbox", "wh_inbox_state", "wh_inbox_state_seed_todo", "wh_inbox_state_seed_cursor"));
      Console.WriteLine($"[162] calls={r.Calls} seq_tup_read={r.SequentialRows}");

      await Assert.That(await _scalarAsync(c, "SELECT count(*) FROM public.wh_inbox_state;"))
        .IsEqualTo((long)ROWS);
      await _assertLinearAsync(r.SequentialRows);
    } finally {
      await _execAsync(c, @"
        DELETE FROM public.wh_inbox_state;
        DELETE FROM public.wh_inbox;
        -- The backfill's guard looks for the columns 162 moves out to the side table, so the
        -- pre-migration shape has to come back or the only reachable path is that guard.
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS processed_at TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS instance_id UUID;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS lease_expiry TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS attempts INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS scheduled_for TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS failure_reason INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS error TEXT;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS chain_emitted_at TIMESTAMPTZ;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS status INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS received_at TIMESTAMPTZ DEFAULT NOW();
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS partition_number INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS priority INTEGER DEFAULT 0;
        ALTER TABLE public.wh_inbox ADD COLUMN IF NOT EXISTS is_event BOOLEAN DEFAULT TRUE;
        DROP TABLE IF EXISTS public.wh_inbox_state_seed_todo;
        DROP TABLE IF EXISTS public.wh_inbox_state_seed_cursor;");
    }
  }
