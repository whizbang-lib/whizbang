using Npgsql;
using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;
using Whizbang.Core.Messaging;
using Whizbang.Core.ValueObjects;

namespace Whizbang.Data.EFCore.Postgres.Tests;

/// <summary>
/// #2352: every digest path counts events by one shared rule (the <c>__DIGEST_ELIGIBLE__</c> migration constant), and
/// every checkpoint count by its companion (<c>__INTEGRITY_COUNTED__</c>), so two paths never disagree about the same
/// event. These are the paths whose copies disagreed: the digest seed, the consumer's checkpoint count, and the
/// one-time removal of digest buckets left with no events.
/// </summary>
/// <code-under-test>src/Whizbang.Data.Postgres/Migrations/453_DigestPathsShareOneEligibilityRule.sql</code-under-test>
/// <docs>resilience/stream-integrity#one-eligibility-rule</docs>
[Category("Integration")]
[Category("Shard2")]
public class DigestEligibilitySqlTests : EFCoreTestBase {
  private const string TYPE = "Contracts.EligibilityProbe, Contracts";
  private const string EXEMPT_TYPE = "Whizbang.Core.SystemEvents.EventAudited, Whizbang.Core";

  private static IWorkCoordinator _coordinator(WorkCoordinationDbContext ctx) =>
    new EFCoreWorkCoordinator<WorkCoordinationDbContext>(ctx, Whizbang.Core.Serialization.JsonContextRegistry.CreateCombinedOptions());

  [Test]
  public async Task TheSeed_LeavesOutAtMostOnceAndExemptEvents_AsEveryOtherFoldDoesAsync() {
    await using var conn = await _openAsync();
    var stream = TrackedGuid.New().Value;
    await _seedAsync(conn, null, stream, TYPE, seq: null, flags: 0);
    await _seedAsync(conn, null, stream, TYPE, seq: null, flags: (int)EventFlags.AtMostOnce);
    await _seedAsync(conn, null, stream, EXEMPT_TYPE, seq: null, flags: 0);
    await _execAsync(conn, $"DELETE FROM wh_stream_digests WHERE stream_id = '{stream}'");
    await _execAsync(conn, $"""
      CREATE TABLE wh_stream_digest_seed_todo (seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, stream_id UUID NOT NULL);
      CREATE TABLE wh_stream_digest_seed_cursor (only_row BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (only_row), last_seq BIGINT NOT NULL DEFAULT 0);
      INSERT INTO wh_stream_digest_seed_cursor (only_row, last_seq) VALUES (TRUE, 0);
      INSERT INTO wh_stream_digest_seed_todo (stream_id) VALUES ('{stream}');
      """);

    await _execAsync(conn, "SELECT wh_seed_stream_digests_batch(100)");

    await Assert.That(await _bucketsAsync(conn, stream)).IsEquivalentTo([$"{TYPE}|1"])
      .Because("the seed folds what every digest fold folds: not the at-most-once event, not the audit record");
  }

  [Test]
  public async Task TheConsumersCheckpointCount_LeavesOutAtMostOnceEvents_AsTheOriginsCountDoesAsync() {
    await using var conn = await _openAsync();
    await using var ctx = CreateDbContext();
    var origin = TrackedGuid.New().Value;
    await _seedAsync(conn, origin, TrackedGuid.New().Value, TYPE, seq: 1, flags: 0);
    await _seedAsync(conn, origin, TrackedGuid.New().Value, TYPE, seq: 2, flags: (int)EventFlags.AtMostOnce);
    await _seedAsync(conn, origin, TrackedGuid.New().Value, TYPE, seq: 3, flags: (int)EventFlags.Ephemeral);
    await _seedAsync(conn, origin, TrackedGuid.New().Value, EXEMPT_TYPE, seq: 4, flags: 0);

    var counts = await _coordinator(ctx).CountReceivedFromOriginAsync(origin, 0, 10);

    await Assert.That(counts.Select(c => $"{c.TenantScope}|{c.EventType}|{c.Count}").ToList())
      .IsEquivalentTo([$"tenant-a|{TYPE}|2"])
      .Because("the at-most-once event is not counted (the origin's count leaves it out); the ephemeral one is, as on the origin");
  }

  [Test]
  public async Task DigestBucketsWithNoEligibleEvents_AreRemoved_AndBucketsWithEventsKeptAsync() {
    await using var conn = await _openAsync();
    var kept = TrackedGuid.New().Value;
    var orphaned = TrackedGuid.New().Value;
    var onlyIneligible = TrackedGuid.New().Value;
    await _seedAsync(conn, null, kept, TYPE, seq: null, flags: 0);
    await _seedAsync(conn, null, onlyIneligible, TYPE, seq: null, flags: (int)EventFlags.Ephemeral);
    await _execAsync(conn, $"""
      INSERT INTO wh_stream_digests (origin_service_id, scope_tenant, event_type, stream_id, digest_lo, digest_hi, event_count)
      VALUES ('00000000-0000-0000-0000-000000000000', 'tenant-a', '{TYPE}', '{orphaned}', 11, 12, 2),
             ('00000000-0000-0000-0000-000000000000', 'tenant-a', '{TYPE}', '{onlyIneligible}', 13, 14, 1),
             ('00000000-0000-0000-0000-000000000000', 'tenant-a', '{TYPE}', '{kept}', 15, 16, 1)
      ON CONFLICT DO NOTHING
      """);

    await _execAsync(conn, "SELECT wh_remove_eventless_stream_digests()");

    await Assert.That(await _bucketsAsync(conn, orphaned)).IsEmpty();
    await Assert.That(await _bucketsAsync(conn, onlyIneligible)).IsEmpty()
      .Because("an event the rule does not count holds no bucket up");
    await Assert.That(await _bucketsAsync(conn, kept)).IsEquivalentTo([$"{TYPE}|1"]);
  }

  // ── helpers ──

  private async Task<NpgsqlConnection> _openAsync() {
    var conn = new NpgsqlConnection(ConnectionString);
    await conn.OpenAsync();
    return conn;
  }

  private static async Task _seedAsync(NpgsqlConnection conn, Guid? origin, Guid stream, string type, long? seq, int flags) {
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = """
      INSERT INTO wh_event_store
        (event_id, stream_id, aggregate_id, aggregate_type, event_type, scope, version,
         commit_sequence, flags, created_at, origin_service_id, origin_commit_sequence)
      VALUES (@event, @stream, @stream, 'TestAggregate', @type, jsonb_build_object('t', 'tenant-a'),
              (SELECT COALESCE(MAX(version), 0) + 1 FROM wh_event_store WHERE stream_id = @stream),
              nextval('wh_commit_seq'), @flags, NOW() - INTERVAL '2 hours', @origin, @seq)
      """;
    cmd.Parameters.AddWithValue("event", TrackedGuid.New().Value);
    cmd.Parameters.AddWithValue(nameof(stream), stream);
    cmd.Parameters.AddWithValue(nameof(type), type);
    cmd.Parameters.AddWithValue(nameof(flags), flags);
    cmd.Parameters.Add(new NpgsqlParameter(nameof(origin), NpgsqlTypes.NpgsqlDbType.Uuid) { Value = (object?)origin ?? DBNull.Value });
    cmd.Parameters.Add(new NpgsqlParameter(nameof(seq), NpgsqlTypes.NpgsqlDbType.Bigint) { Value = (object?)seq ?? DBNull.Value });
    await cmd.ExecuteNonQueryAsync();
  }

  private static async Task<List<string>> _bucketsAsync(NpgsqlConnection conn, Guid stream) {
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = "SELECT event_type, event_count FROM wh_stream_digests WHERE stream_id = @s ORDER BY event_type";
    cmd.Parameters.AddWithValue("s", stream);
    var rows = new List<string>();
    await using var reader = await cmd.ExecuteReaderAsync();
    while (await reader.ReadAsync()) {
      rows.Add($"{reader.GetString(0)}|{reader.GetInt32(1)}");
    }
    return rows;
  }

  private static async Task _execAsync(NpgsqlConnection conn, string sql) {
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = sql;
    await using var reader = await cmd.ExecuteReaderAsync();
    while (await reader.ReadAsync()) {
      // drained: some statements return rows
    }
  }
}
