using Npgsql;
using NpgsqlTypes;
using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;
using Whizbang.Core.Messaging;
using Whizbang.Core.ValueObjects;

namespace Whizbang.Data.EFCore.Postgres.Tests;

/// <summary>
/// #2588: an event an operator excluded from integrity (<see cref="EventFlags.IntegrityExcluded"/>) leaves every fold
/// through the one eligibility rule (version 2), with no path of its own: the digest seed, the full recompute and the
/// sweep's heal, the chunk-bounded fold, the type and windowed folds, the epoch fold, the held fold (also when the flag is
/// set on a row already held), the checkpoint count and the removal of buckets with nothing left in them. Each test
/// pairs the flagged event with an unflagged one in the same place, so an assertion cannot pass by folding nothing.
/// </summary>
/// <code-under-test>src/Whizbang.Data.Postgres/Migrations/662_TheEligibilityRuleLeavesOutExcludedEvents.sql</code-under-test>
/// <docs>resilience/integrity-exclusions</docs>
[Category("Integration")]
[Category("Shard2")]
public class IntegrityExcludedFoldTests : EFCoreTestBase {
  private const string TYPE = "Contracts.ExclusionProbe, Contracts";
  private const string TENANT = "tenant-x";
  private const int EXCLUDED = (int)EventFlags.IntegrityExcluded;

  private static IWorkCoordinator _coordinator(WorkCoordinationDbContext ctx) =>
    new EFCoreWorkCoordinator<WorkCoordinationDbContext>(ctx, Whizbang.Core.Serialization.JsonContextRegistry.CreateCombinedOptions());

  [Test]
  public async Task TheSeed_LeavesOutAnExcludedEventAsync() {
    await using var conn = await _openAsync();
    var stream = TrackedGuid.New().Value;
    await _seedAsync(conn, null, stream, seq: null, flags: 0);
    await _seedAsync(conn, null, stream, seq: null, flags: EXCLUDED);
    await _execAsync(conn, $"""
      CREATE TABLE wh_stream_digest_seed_todo (seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, stream_id UUID NOT NULL);
      CREATE TABLE wh_stream_digest_seed_cursor (only_row BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (only_row), last_seq BIGINT NOT NULL DEFAULT 0);
      INSERT INTO wh_stream_digest_seed_cursor (only_row, last_seq) VALUES (TRUE, 0);
      INSERT INTO wh_stream_digest_seed_todo (stream_id) VALUES ('{stream}');
      """);

    await _execAsync(conn, "SELECT wh_seed_stream_digests_batch(100)");

    await Assert.That(await _bucketCountAsync(conn, stream)).IsEqualTo(1)
      .Because("the seed folds the unflagged event and leaves the excluded one out");
  }

  [Test]
  public async Task TheFullRecompute_AndTheSweepsHeal_LeaveOutAnExcludedEventAsync() {
    await using var conn = await _openAsync();
    await using var ctx = CreateDbContext();
    var stream = TrackedGuid.New().Value;
    await _seedAsync(conn, null, stream, seq: null, flags: 0);
    await _seedAsync(conn, null, stream, seq: null, flags: EXCLUDED);

    var recomputed = await _coordinator(ctx).ComputeStreamDigestsAsync(null, [TYPE], TimeSpan.Zero);
    await _coordinator(ctx).VerifyDigestTableAsync(TimeSpan.Zero);

    await Assert.That(recomputed.Single(d => d.StreamId == stream).EventCount).IsEqualTo(1)
      .Because("the full recompute counts by the rule");
    await Assert.That(await _bucketCountAsync(conn, stream)).IsEqualTo(1)
      .Because("the sweep heals the table to what the rule counts, so it never writes the excluded event back in");
  }

  [Test]
  public async Task TheChunkFold_TheTypeFolds_AndTheWindowedFolds_LeaveOutAnExcludedEventAsync() {
    await using var conn = await _openAsync();
    await using var ctx = CreateDbContext();
    var coordinator = _coordinator(ctx);
    var origin = TrackedGuid.New().Value;
    var stream = TrackedGuid.New().Value;
    await _seedAsync(conn, origin, stream, seq: 1, flags: 0);
    await _seedAsync(conn, origin, stream, seq: 2, flags: EXCLUDED);

    var chunk = await coordinator.ComputeStreamDigestsForChunkAsync(origin, [stream], 0, 10, TimeSpan.Zero);
    var types = await coordinator.ComputeTypeDigestsAsync(origin, [TYPE], TimeSpan.Zero);
    var typeWindow = await coordinator.ComputeTypeDigestsWindowedAsync(origin, [TYPE], 0, 10, TimeSpan.Zero);
    var streamWindow = await coordinator.ComputeStreamDigestsWindowedAsync(origin, [TYPE], 0, 10, null, 100, TimeSpan.Zero);

    await Assert.That(chunk!.Single().EventCount).IsEqualTo(1);
    await Assert.That(types.Single().EventCount).IsEqualTo(1);
    await Assert.That(typeWindow!.Digests.Single().EventCount).IsEqualTo(1);
    await Assert.That(streamWindow!.Digests.Single().EventCount).IsEqualTo(1)
      .Because("every fold the compare reads counts by the rule");
  }

  [Test]
  public async Task TheEpochFold_LeavesOutAnExcludedEventAsync() {
    await using var conn = await _openAsync();
    var origin = TrackedGuid.New().Value;
    await _seedAsync(conn, origin, TrackedGuid.New().Value, seq: 1, flags: 0);
    await _seedAsync(conn, origin, TrackedGuid.New().Value, seq: 2, flags: EXCLUDED);

    await using var cmd = conn.CreateCommand();
    cmd.CommandText = "SELECT COALESCE(SUM(b_cnt), 0) FROM _wh_epoch_buckets(@o, 0, 10)";
    cmd.Parameters.AddWithValue("o", origin);
    var counted = Convert.ToInt64(await cmd.ExecuteScalarAsync(), System.Globalization.CultureInfo.InvariantCulture);

    await Assert.That(counted).IsEqualTo(1L).Because("a sealed epoch folds what the rule counts");
  }

  [Test]
  public async Task TheHeldFold_LeavesOutAnExcludedEvent_AndDropsAHeldOneWhenItIsFlaggedAsync() {
    await using var conn = await _openAsync();
    var origin = TrackedGuid.New().Value;
    await _seedAsync(conn, origin, TrackedGuid.New().Value, seq: null, flags: 0);
    await _seedAsync(conn, origin, TrackedGuid.New().Value, seq: null, flags: EXCLUDED);
    var flaggedLater = await _seedAsync(conn, origin, TrackedGuid.New().Value, seq: null, flags: 0);

    var before = await _heldCountAsync(conn, origin);
    await _execAsync(conn, $"UPDATE wh_event_store SET flags = flags | {EXCLUDED} WHERE event_id = '{flaggedLater}'");
    var after = await _heldCountAsync(conn, origin);

    await Assert.That(before).IsEqualTo(2L).Because("an event stored flagged is never held");
    await Assert.That(after).IsEqualTo(1L).Because("flagging a held event takes it out of the held fold through its trigger");
  }

  [Test]
  public async Task TheCheckpointCount_LeavesOutAnExcludedEventAsync() {
    await using var conn = await _openAsync();
    await using var ctx = CreateDbContext();
    var origin = TrackedGuid.New().Value;
    await _seedAsync(conn, origin, TrackedGuid.New().Value, seq: 1, flags: 0);
    await _seedAsync(conn, origin, TrackedGuid.New().Value, seq: 2, flags: EXCLUDED);

    var counts = await _coordinator(ctx).CountReceivedFromOriginAsync(origin, 0, 10);

    await Assert.That(counts.Select(c => $"{c.TenantScope}|{c.EventType}|{c.Count}").ToList())
      .IsEquivalentTo([$"{TENANT}|{TYPE}|1"]);
  }

  [Test]
  public async Task ABucketHoldingOnlyExcludedEvents_IsRemovedAsEventlessAsync() {
    await using var conn = await _openAsync();
    var kept = TrackedGuid.New().Value;
    var onlyExcluded = TrackedGuid.New().Value;
    await _seedAsync(conn, null, kept, seq: null, flags: 0);
    await _seedAsync(conn, null, onlyExcluded, seq: null, flags: EXCLUDED);
    await _execAsync(conn, $"""
      INSERT INTO wh_stream_digests (origin_service_id, scope_tenant, event_type, stream_id, digest_lo, digest_hi, event_count)
      VALUES ('00000000-0000-0000-0000-000000000000', '{TENANT}', '{TYPE}', '{onlyExcluded}', 13, 14, 1),
             ('00000000-0000-0000-0000-000000000000', '{TENANT}', '{TYPE}', '{kept}', 15, 16, 1)
      ON CONFLICT DO NOTHING
      """);

    await _execAsync(conn, "SELECT wh_remove_eventless_stream_digests()");

    await Assert.That(await _bucketCountAsync(conn, onlyExcluded)).IsNull();
    await Assert.That(await _bucketCountAsync(conn, kept)).IsEqualTo(1);
  }

  [Test]
  public async Task AnEventAppendedWithTheFlag_IsNotFoldedIntoItsStreamDigestAsync() {
    await using var conn = await _openAsync();
    var kept = TrackedGuid.New().Value;
    var excluded = TrackedGuid.New().Value;

    await _appendAsync(conn, kept, flags: 0);
    await _appendAsync(conn, excluded, flags: EXCLUDED);

    await Assert.That(await _bucketCountAsync(conn, kept)).IsEqualTo(1);
    await Assert.That(await _bucketCountAsync(conn, excluded)).IsNull()
      .Because("the append folds by the rule");
  }

  // ── helpers ──

  private async Task<NpgsqlConnection> _openAsync() {
    var conn = new NpgsqlConnection(ConnectionString);
    await conn.OpenAsync();
    return conn;
  }

  private static async Task<Guid> _seedAsync(NpgsqlConnection conn, Guid? origin, Guid stream, long? seq, int flags) {
    var id = TrackedGuid.New().Value;
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = """
      INSERT INTO wh_event_store
        (event_id, stream_id, aggregate_id, aggregate_type, event_type, scope, version,
         commit_sequence, flags, created_at, origin_service_id, origin_commit_sequence)
      VALUES (@event, @stream, @stream, 'TestAggregate', @type, jsonb_build_object('t', @tenant),
              (SELECT COALESCE(MAX(version), 0) + 1 FROM wh_event_store WHERE stream_id = @stream),
              nextval('wh_commit_seq'), @flags, NOW() - INTERVAL '2 hours', @origin, @seq)
      """;
    cmd.Parameters.AddWithValue("event", id);
    cmd.Parameters.AddWithValue(nameof(stream), stream);
    cmd.Parameters.AddWithValue("type", TYPE);
    cmd.Parameters.AddWithValue("tenant", TENANT);
    cmd.Parameters.AddWithValue(nameof(flags), flags);
    cmd.Parameters.Add(new NpgsqlParameter(nameof(origin), NpgsqlDbType.Uuid) { Value = (object?)origin ?? DBNull.Value });
    cmd.Parameters.Add(new NpgsqlParameter(nameof(seq), NpgsqlDbType.Bigint) { Value = (object?)seq ?? DBNull.Value });
    await cmd.ExecuteNonQueryAsync();
    return id;
  }

  private static async Task _appendAsync(NpgsqlConnection conn, Guid stream, int flags) {
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = """
      SELECT wh_append_event(@id, @stream, @stream, 'TestAggregate', @type, '{}'::jsonb, '{}'::jsonb,
                             jsonb_build_object('t', @tenant), NOW(), @flags)
      """;
    cmd.Parameters.AddWithValue("id", TrackedGuid.New().Value);
    cmd.Parameters.AddWithValue(nameof(stream), stream);
    cmd.Parameters.AddWithValue("type", TYPE);
    cmd.Parameters.AddWithValue("tenant", TENANT);
    cmd.Parameters.AddWithValue(nameof(flags), flags);
    await using var reader = await cmd.ExecuteReaderAsync();
    while (await reader.ReadAsync()) {
      // drained
    }
  }

  private static async Task<int?> _bucketCountAsync(NpgsqlConnection conn, Guid stream) {
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = "SELECT SUM(event_count)::int FROM wh_stream_digests WHERE stream_id = @s";
    cmd.Parameters.AddWithValue("s", stream);
    var value = await cmd.ExecuteScalarAsync();
    return value is DBNull or null ? null : (int)value;
  }

  private static async Task<long> _heldCountAsync(NpgsqlConnection conn, Guid origin) {
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = "SELECT COALESCE(SUM(event_count), 0) FROM wh_unsequenced_received_type_digests(@o, @t, INTERVAL '0')";
    cmd.Parameters.AddWithValue("o", origin);
    cmd.Parameters.AddWithValue("t", new[] { TYPE });
    return Convert.ToInt64(await cmd.ExecuteScalarAsync(), System.Globalization.CultureInfo.InvariantCulture);
  }

  private static async Task _execAsync(NpgsqlConnection conn, string sql) {
    await using var cmd = conn.CreateCommand();
    cmd.CommandText = sql;
    await using var reader = await cmd.ExecuteReaderAsync();
    while (await reader.ReadAsync()) {
      // drained: some statements return rows
    }
  }
}
